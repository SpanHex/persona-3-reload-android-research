"""
Code Generator: LLVM IR -> AArch64 Machine Code & Dispatch Table
Implements backend compilation matching Bloodborne-android-rebuild-tool:
- Target triple: aarch64-unknown-linux-android30
- Architecture features: +v8.2a,+lse,+crc,+fp-armv8,+neon (Snapdragon 7s Gen 2 / Realme 12 Pro+)
- Position-Independent Code (PIC) for Bionic dynamic loader
- Generates bbr_units[] dispatch table and Recomp ABI v2 metadata
- Provides host JIT execution engine for functional oracle verification
"""

import os
import json
import ctypes
import llvmlite.ir as ir
import llvmlite.binding as llvm
from typing import List, Dict, Tuple, Optional

# Initialize LLVM targets
llvm.initialize_all_targets()
llvm.initialize_all_asmprinters()

class CodeGenerator:
    def __init__(self, target_cpu: str = "generic", opt_level: int = 2):
        self.target_triple = "aarch64-unknown-linux-android30"
        self.target_cpu = target_cpu
        self.features = "+v8.2a,+lse,+crc,+fp-armv8,+neon"
        self.opt_level = opt_level

        # Create AArch64 TargetMachine
        self.target = llvm.Target.from_triple(self.target_triple)
        self.target_machine = self.target.create_target_machine(
            cpu=self.target_cpu,
            features=self.features,
            opt=self.opt_level,
            reloc="pic"
        )

        # Host TargetMachine for test execution
        self.host_target = llvm.Target.from_default_triple()
        self.host_target_machine = self.host_target.create_target_machine(opt=self.opt_level)

    def verify_and_parse(self, ir_module: ir.Module) -> llvm.ModuleRef:
        """Parses and verifies LLVM IR string"""
        ir_str = str(ir_module)
        mod_parsed = llvm.parse_assembly(ir_str)
        mod_parsed.verify()
        return mod_parsed

    def emit_aarch64_assembly(self, mod_parsed: llvm.ModuleRef) -> str:
        """Emits native AArch64 GNU assembly (.s)"""
        return self.target_machine.emit_assembly(mod_parsed)

    def emit_aarch64_object(self, mod_parsed: llvm.ModuleRef) -> bytes:
        """Emits native AArch64 ELF object file (.o)"""
        return self.target_machine.emit_object(mod_parsed)

    def generate_dispatch_table_c(self, discovered_addrs: List[int]) -> str:
        """
        Generates C source for bbr_units[] array matching Bloodborne guest_cpu_aot.cpp
        """
        lines = [
            "// SPDX-License-Identifier: MIT",
            "// Auto-generated by P3R Recompiler (Recomp ABI v2)",
            "#include <stdint.h>",
            "#include <stddef.h>",
            "",
            "typedef struct GuestState GuestState;",
            "typedef void (*bbr_func_t)(GuestState*);",
            "",
            "typedef struct RecompUnit {",
            "    uint64_t vaddr;",
            "    bbr_func_t func;",
            "} RecompUnit;",
            "",
        ]

        # Declare extern prototypes
        for addr in sorted(discovered_addrs):
            lines.append(f"extern void bbr_{hex(addr)[2:]}(GuestState*);")

        lines.append("")
        lines.append(f"const size_t g_bbr_unit_count = {len(discovered_addrs)};")
        lines.append("const RecompUnit g_bbr_units[] = {")
        for addr in sorted(discovered_addrs):
            lines.append(f"    {{ 0x{hex(addr)[2:]}ULL, bbr_{hex(addr)[2:]} }},")
        lines.append("};")
        lines.append("")

        # Binary search lookup function
        lines.append("bbr_func_t bbr_lookup(uint64_t vaddr) {")
        lines.append("    int low = 0;")
        lines.append("    int high = (int)g_bbr_unit_count - 1;")
        lines.append("    while (low <= high) {")
        lines.append("        int mid = low + (high - low) / 2;")
        lines.append("        if (g_bbr_units[mid].vaddr == vaddr) return g_bbr_units[mid].func;")
        lines.append("        if (g_bbr_units[mid].vaddr < vaddr) low = mid + 1;")
        lines.append("        else high = mid - 1;")
        lines.append("    }")
        lines.append("    return NULL; // Miss")
        lines.append("}")

        return "\n".join(lines)

    def create_host_engine(self, ir_module: ir.Module) -> Tuple[llvm.ExecutionEngine, llvm.ModuleRef]:
        """Creates an in-memory MCJIT execution engine on the host"""
        mod_parsed = self.verify_and_parse(ir_module)
        backing_mod = llvm.parse_assembly("")
        engine = llvm.create_mcjit_compiler(backing_mod, self.host_target_machine)
        engine.add_module(mod_parsed)
        engine.finalize_object()
        return engine, mod_parsed
